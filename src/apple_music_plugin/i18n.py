def language(locale):
    return "es" if str(locale).lower().replace("_", "-").split("-")[0] == "es" else "en"


def translate(locale, msgid, **values):
    result = ES.get(msgid, msgid) if language(locale) == "es" else msgid
    return result.format(**values) if values else result


def settings_text(document, locale):
    """Translate presentation fields without changing control keys or values."""
    text_keys = {"title", "label", "description", "text", "message", "eyebrow"}
    def visit(value, key=None):
        if key == "values":
            return value
        if isinstance(value, dict):
            return {name: visit(item, name) for name, item in value.items()}
        if isinstance(value, list):
            return [visit(item, key) for item in value]
        if isinstance(value, str) and key in text_keys | {"notices"}:
            return translate(locale, value)
        return value
    return visit(document)
